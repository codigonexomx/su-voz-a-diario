import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const argument = name => process.argv.find(value => value.startsWith(`--${name}=`))?.split('=')[1];
const today = argument('from') || new Intl.DateTimeFormat('en-CA', {
    timeZone: 'America/Mexico_City', year: 'numeric', month: '2-digit', day: '2-digit',
}).format(new Date());
const days = Number(argument('days') || 30);
if (!/^\d{4}-\d{2}-\d{2}$/.test(today) || !Number.isInteger(days) || days < 1 || days > 366) throw new Error('Invalid coverage interval');
const catalog = JSON.parse(readFileSync(fileURLToPath(new URL('../data/readings/index.json', import.meta.url)), 'utf8'));
const available = new Set(catalog.map(item => item.date));
const missing = [];
const start = Date.parse(`${today}T12:00:00Z`);
if (!Number.isFinite(start)) throw new Error('Invalid date');
for (let offset = 0; offset < days; offset++) {
    const date = new Date(start + offset * 86400000).toISOString().slice(0, 10);
    if (!available.has(date)) missing.push(date);
}
const last = [...available].sort().at(-1);
console.log(`Reading coverage: ${today}, ${days} days; last scheduled date: ${last}`);
if (missing.length) { console.error(`Missing editorial readings: ${missing.join(', ')}`); process.exitCode = 1; }
else console.log('OK: upcoming daily readings are scheduled.');
if (Date.parse(`${last}T12:00:00Z`) - start < 120 * 86400000) console.warn('Editorial action required: prepare approved readings beyond the current calendar. No content is generated by this check.');
